/* ----------------------------------------------------------------------------
   MAP BLOCK - crumbs + map + legend + panel, no outer <section>/heading, so
   a parent section (e.g. WheatHarvest.jsx's own "Every Field on the Map"
   section) can drop this in next to its own copy/photos without a
   duplicate title.
---------------------------------------------------------------------------- */
export function WheatFieldsMapBlock() {
  const [level, setLevel] = useState("india");
  const [village, setVillage] = useState(null);
  const [field, setField] = useState(null);
  const [hoverField, setHoverField] = useState(null);
  // which of the two (non-adjacent) districts the camera is zoomed into,
  // while still nominally "at" the district level/breadcrumb
  const [focusedDistrict, setFocusedDistrict] = useState(null);

  const goto = useCallback((key) => {
    setLevel(key);
    setField(null);
    setHoverField(null);
    setFocusedDistrict(null);
    if (key !== "village") setVillage(null);
  }, []);

  const pickVillage = useCallback((key) => { setVillage(key); setLevel("village"); setField(null); setFocusedDistrict(null); }, []);
  const pickState = useCallback(() => setLevel((l) => (l === "india" ? "punjab" : "district")), []);
  // clicking a field at district level zooms into its village AND pins that
  // field, so the click actually goes somewhere instead of doing nothing.
  const zoomToField = useCallback((villageKey, fieldId) => {
    setVillage(villageKey); setLevel("village"); setField(fieldId); setFocusedDistrict(null);
  }, []);
  // clicking Ludhiana or Faridkot's shape at district level zooms tight into
  // just that district's villages (fields are illegible specks zoomed out to
  // both districts at once) without leaving the district step.
  const focusDistrict = useCallback((name) => setFocusedDistrict(name), []);
  // "zoom out" backs off the district focus one step before popping levels.
  const zoomOut = useCallback(() => {
    if (level === "district" && focusedDistrict) { setFocusedDistrict(null); return; }
    goto(LEVELS[Math.max(0, LEVELS.indexOf(level) - 1)]);
  }, [level, focusedDistrict, goto]);

  const legend = level === "village"
    ? MILLERS.map((n) => [millerColor(n), n])
    : null;

  return (
    <div>
      <div className="flex flex-wrap items-center justify-between gap-3 mb-4">
        <Crumbs level={level} village={village} onGo={goto} />
        <AnimatePresence>
          {level !== "india" && (
            <motion.button
              initial={{ opacity: 0, x: 8 }} animate={{ opacity: 1, x: 0 }} exit={{ opacity: 0, x: 8 }}
              onClick={zoomOut}
              className="px-3 py-1.5 rounded"
              style={{ fontFamily: FONT_DATA, fontSize: 10, letterSpacing: ".1em", color: C.mute, border: `1px solid ${C.line}` }}
            >
              &larr; ZOOM OUT
            </motion.button>
          )}
        </AnimatePresence>
      </div>

      <div className="grid gap-6 lg:grid-cols-5 items-stretch">
          <div className="lg:col-span-3">
            <DrillMap
              level={level}
              village={village}
              focusedDistrict={focusedDistrict}
              selected={field}
              onPickState={pickState}
              onPickVillage={pickVillage}
              onPickField={setField}
              onHoverField={setHoverField}
              onZoomToField={zoomToField}
              onFocusDistrict={focusDistrict}
            />

            {legend ? (
              <div className="mt-4 flex flex-wrap items-center gap-x-5 gap-y-2">
                {legend.map(([c, l]) => (
                  <span key={l} className="flex items-center gap-2" style={{ fontFamily: FONT_DATA, fontSize: 10, color: C.mute }}>
                    <span style={{ width: 10, height: 10, background: c, borderRadius: 2 }} />
                    {l.toUpperCase()}
                  </span>
                ))}
              </div>
            ) : (
              <div className="mt-4 rounded-lg overflow-hidden" style={{ border: `1px solid ${C.line}` }}>
                <div className="grid grid-cols-2" style={{ background: C.field }}>
                  <div className="px-4 py-2" style={{ fontFamily: FONT_DATA, fontSize: 10.5, color: "#fff", fontWeight: 700, letterSpacing: ".08em" }}>MILLER</div>
                  <div className="px-4 py-2 text-right" style={{ fontFamily: FONT_DATA, fontSize: 10.5, color: "#fff", fontWeight: 700, letterSpacing: ".08em" }}>IN MT</div>
                </div>
                {MILLER_ORDER.map((n, i) => (
                  <div key={n} className="grid grid-cols-2" style={{ borderTop: i ? `1px solid ${C.line}` : "none", background: i % 2 ? C.paperDim : "#fff" }}>
                    <div className="px-4 py-2.5 flex items-center gap-2" style={{ fontFamily: FONT_DATA, fontSize: 12, color: C.ink, fontWeight: 600 }}>
                      <span style={{ width: 9, height: 9, background: millerColor(n), borderRadius: 2, flexShrink: 0 }} />
                      {n}
                    </div>
                    <div className="px-4 py-2.5 text-right" style={{ fontFamily: FONT_DATA, fontSize: 12, color: C.mute }}>
                      XXS
                    </div>
                  </div>
                ))}
              </div>
            )}
          </div>

          <div className="lg:col-span-2">
            <Panel level={level} village={village} field={field} hoverField={hoverField} />
          </div>
        </div>
    </div>
  );
}


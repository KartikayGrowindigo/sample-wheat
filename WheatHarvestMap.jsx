/** Bounding box of a list of {lon,lat} points, for fitBounds. */
function pointBounds(points) {
  let w = 180, s = 90, e = -180, n = -90;
  points.forEach(({ lon, lat }) => {
    if (lon < w) w = lon; if (lon > e) e = lon;
    if (lat < s) s = lat; if (lat > n) n = lat;
  });
  return [[w, s], [e, n]];
}

/** Bounding box of a Polygon or MultiPolygon geometry, for fitBounds. */
function geomBounds(geom) {
  let w = 180, s = 90, e = -180, n = -90;
  const rings = geom.type === "MultiPolygon" ? geom.coordinates.flat() : geom.coordinates;
  rings.forEach((ring) =>
    ring.forEach(([x, y]) => {
      if (x < w) w = x; if (x > e) e = x;
      if (y < s) s = y; if (y > n) n = y;
    })
  );
  return [[w, s], [e, n]];
}

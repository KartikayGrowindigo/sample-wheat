/* ============================================================================
   WheatHarvestMap - real basemap drill-down
   India -> Punjab -> project district(s) -> village -> single farmer field

   Mirrors ClearHarvestMap.jsx (the ClearHarvest rice report's map) exactly in
   structure, stack and interaction model. Only the geography and data are
   swapped for the wheat programme.
   ----------------------------------------------------------------------------
   STACK
     maplibre-gl   real vector basemap, camera animation (flyTo / fitBounds)
     framer-motion breadcrumbs, detail panel, legend transitions

   INSTALL
     npm i maplibre-gl
     import "maplibre-gl/dist/maplibre-gl.css";   // required, once, app-wide

   DATA
     wheat-fields.geo.json, wheat-boundaries.geo.json (project-district
     rectangle only), wheat-villages.json and wheat-millers.json are all
     generated from "273 Farmer Data (Clearharvest).xlsx" by
     scripts/build_fields.py - rerun that script after editing the Excel.
     No real field-boundary/KML export exists for this programme (only a
     point lat/lon per farmer), so field polygons are synthetic parcels
     built from each point + its acreage - see the script's docstring for
     the village-blob / Voronoi / erosion / jitter pipeline. `acres` on each
     feature is measured off the drawn polygon; `acresExcel` is the source
     sheet's value, kept only for reference/QA.
     wheat-boundaries.geo.json  Punjab is still a rough placeholder
                          rectangle - TODO: swap for a real state polygon
                          (dissolved from district polygons the same way
                          ClearHarvestMap.jsx handles Telangana, if needed).
                          The project-district rectangle *is* sized to the
                          real data's extent (Ludhiana + Faridkot villages).

   BASEMAP AND INDIAN BOUNDARIES - read before shipping
     The default style below (CARTO Positron) is OSM-derived and depicts the
     Line of Control in Jammu & Kashmir per international convention, not
     India's official claim line. Maps published in India are expected to show
     the full claimed boundary. For a deliverable circulating in India, point
     BASEMAP_STYLE at an India-compliant source - Mappls (MapmyIndia) or Google
     Maps served with region=IN - or clear the current basemap with your legal
     team. Swapping it is a one-line change.
============================================================================ */


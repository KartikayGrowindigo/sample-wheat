/** Bounding box of a FeatureCollection, for fitBounds. */
function fcBounds(fc) {
  let w = 180, s = 90, e = -180, n = -90;
  fc.features.forEach((f) =>
    f.geometry.coordinates[0].forEach(([x, y]) => {
      if (x < w) w = x; if (x > e) e = x;
      if (y < s) s = y; if (y > n) n = y;
    })
  );
  return [[w, s], [e, n]];
}

/* One-time global keyframe for the village-pin pulsing halo (injected once,
   guarded by id, since this component owns no app-wide stylesheet). */
function ensurePulseKeyframes() {
  if (document.getElementById("wh-village-pulse-style")) return;
  const style = document.createElement("style");
  style.id = "wh-village-pulse-style";
  style.textContent = `@keyframes wh-village-pulse {
    0%   { transform: scale(0.6); opacity: 0.6; }
    70%  { transform: scale(2.3); opacity: 0; }
    100% { transform: scale(2.3); opacity: 0; }
  }`;
  document.head.appendChild(style);
}

/* ----------------------------------------------------------------------------
   MAP
   One MapLibre instance for the whole drill-down. Layers are added once on
   load; level changes only move the camera and toggle layer visibility, which
   is far smoother than tearing sources down and rebuilding them.
---------------------------------------------------------------------------- */
function DrillMap({ level, village, focusedDistrict, selected, onPickState, onPickVillage, onPickField, onHoverField, onZoomToField, onFocusDistrict }) {
  const holder = useRef(null);
  const map = useRef(null);
  const markers = useRef([]);
  const [ready, setReady] = useState(false);
  const popup = useRef(null);
  const levelRef = useRef(level);
  const villageRef = useRef(village);
  const focusedDistrictRef = useRef(focusedDistrict);
  useEffect(() => { levelRef.current = level; }, [level]);
  useEffect(() => { villageRef.current = village; }, [village]);
  useEffect(() => { focusedDistrictRef.current = focusedDistrict; }, [focusedDistrict]);

  /** Re-fit the camera to whatever the current drill level should be
   *  looking at, reading level/village/focusedDistrict off refs so it can
   *  be called imperatively (from a ResizeObserver) as well as from the
   *  level-change effect below - both need the exact same "what should be
   *  on screen right now" logic. */
  const refitCamera = useCallback((m, opts = {}) => {
    const lvl = levelRef.current;
    if (lvl === "village" && villageRef.current) {
      m.fitBounds(fcBounds(villageFC(villageRef.current)), { padding: 70, duration: 0, essential: true, ...opts });
    } else if (lvl === "district" && focusedDistrictRef.current) {
      const districtVillages = VILLAGES.filter((v) => v.district === focusedDistrictRef.current);
      m.fitBounds(pointBounds(districtVillages.length ? districtVillages : VILLAGES), { padding: 60, duration: 0, essential: true, ...opts });
    } else {
      const cam = CAMERA[lvl] || CAMERA.india;
      m.fitBounds(cam.bounds, { padding: cam.padding, duration: 0, essential: true, ...opts });
    }
  }, []);

  /* --- init ------------------------------------------------------------- */
  useEffect(() => {
    if (map.current) return;
    ensurePulseKeyframes();
    const m = new MLMap({
      container: holder.current,
      style: BASEMAP_STYLE,
      bounds: CAMERA.india.bounds,
      fitBoundsOptions: { padding: CAMERA.india.padding },
      attributionControl: { compact: true },
      dragRotate: false,
      pitchWithRotate: false,
      maxZoom: 17,
    });
    map.current = m;
    m.on("error", (e) => console.error("MapLibre error:", e?.error || e));
    m.addControl(new NavigationControl({ showCompass: false }), "bottom-right");
    m.addControl(new ScaleControl({ maxWidth: 90, unit: "metric" }), "bottom-left");
    popup.current = new Popup({ closeButton: false, closeOnClick: false, offset: 12, className: "wh-popup" });

    m.on("load", () => {
      const bd = (id) => ({
        type: "Feature",
        properties: {},
        geometry: BOUNDARIES.features.find((f) => f.properties.id === id).geometry,
      });

      /* India - national outline, always on, so the country reads clearly
         at every drill level (not just while zoomed out on it). Dissolved
         from state polygons by scripts/build_india_border.mjs - see that
         file's header for the same OSM/LoC-convention caveat noted above
         for the basemap; swap for a surveyor-general boundary before this
         ships to print. */
      m.addSource("india", { type: "geojson", data: INDIA_BORDER });
      m.addLayer({ id: "in-line", type: "line", source: "india",
        paint: { "line-color": C.husk, "line-width": 2.2 } });

      /* Punjab - the clickable state */
      m.addSource("punjab", { type: "geojson", data: bd("punjab") });
      m.addLayer({ id: "pb-fill", type: "fill", source: "punjab",
        paint: { "fill-color": C.field, "fill-opacity": 0.34 } });
      m.addLayer({ id: "pb-line", type: "line", source: "punjab",
        paint: { "line-color": C.field, "line-width": 1.8 } });

      /* project districts - Ludhiana and Faridkot are real, non-adjacent
         districts (kept as two separate features, each carrying its own
         districtName) so a click can tell which one it landed on and zoom
         tighter into just that district's villages. */
      const districtsFC = {
        type: "FeatureCollection",
        features: BOUNDARIES.features.filter((f) => f.properties.id.startsWith("district-")),
      };
      m.addSource("project-district", { type: "geojson", data: districtsFC });
      m.addLayer({ id: "pd-fill", type: "fill", source: "project-district",
        paint: { "fill-color": C.husk, "fill-opacity": 0 } });
      m.addLayer({ id: "pd-line", type: "line", source: "project-district",
        paint: { "line-color": C.husk, "line-width": 2, "line-opacity": 0 } });

      /* farmer fields - one source, filtered per village. Fill colour keys
         off the procuring miller (no AWD/CRM column exists for this
         programme's sheet); selected/hover feature-state always wins. */
      m.addSource("fields", { type: "geojson", data: FIELDS_FC, promoteId: "id" });
      m.addLayer({
        id: "fld-fill", type: "fill", source: "fields", filter: ["==", ["get", "village"], ""],
        paint: {
          "fill-color": [
            "case",
            ["boolean", ["feature-state", "selected"], false], SELECTED_COLOR,
            ["boolean", ["feature-state", "hover"], false], HOVER_COLOR,
            ["match", ["get", "millerName"], ...MILLERS.flatMap((n) => [n, millerColor(n)]), C.mute],
          ],
          "fill-opacity": [
            "case",
            ["boolean", ["feature-state", "selected"], false], 0.95,
            ["boolean", ["feature-state", "hover"], false], 0.85,
            0.55,
          ],
        },
      });
      m.addLayer({ id: "fld-line", type: "line", source: "fields",
        filter: ["==", ["get", "village"], ""],
        paint: { "line-color": "#ffffff", "line-width": 1 } });

      /* click targets - see ClearHarvestMap.jsx for why the state click is
         gated to the two levels where it means anything and bails when a
         field is under the cursor (MapLibre dispatches to every layer under
         the pointer). */
      m.on("click", "pb-fill", (e) => {
        if (levelRef.current !== "india" && levelRef.current !== "punjab") return;
        const overField = m.queryRenderedFeatures(e.point, { layers: ["fld-fill"] });
        if (overField.length) return;
        if (levelRef.current === "punjab") {
          // Ludhiana & Faridkot (pd-fill) is a highlighted sub-area of Punjab
          // with its own click handler below - let that one drive the zoom
          // instead of double-firing here.
          const overDistrict = m.queryRenderedFeatures(e.point, { layers: ["pd-fill"] });
          if (overDistrict.length) return;
        }
        onPickState();
      });
      m.on("mouseenter", "pb-fill", () => {
        if (levelRef.current === "india" || levelRef.current === "punjab") {
          m.getCanvas().style.cursor = "pointer";
        }
      });
      m.on("mouseleave", "pb-fill", () => (m.getCanvas().style.cursor = ""));

      /* project-district (Ludhiana & Faridkot) is its own clickable sub-area:
         - at punjab level, clicking it (not just anywhere on Punjab) drills
           straight into the district step.
         - at district level (both districts already shown, fields tiny at
           that zoom), clicking one district zooms tight into just that
           district's villages so its fields become legible - without
           advancing the level/breadcrumb, since we're still "at district". */
      m.on("click", "pd-fill", (e) => {
        if (levelRef.current === "punjab") {
          e.preventDefault();
          e.originalEvent.stopPropagation();
          onPickState();
        } else if (levelRef.current === "district") {
          const overField = m.queryRenderedFeatures(e.point, { layers: ["fld-fill"] });
          if (overField.length) return; // let the field's own click handler win
          e.preventDefault();
          e.originalEvent.stopPropagation();
          onFocusDistrict(e.features[0].properties.districtName);
        }
      });
      m.on("mouseenter", "pd-fill", () => {
        if (levelRef.current === "punjab" || levelRef.current === "district") {
          m.getCanvas().style.cursor = "pointer";
        }
      });
      m.on("mouseleave", "pd-fill", () => {
        if (levelRef.current === "punjab" || levelRef.current === "district") {
          m.getCanvas().style.cursor = "";
        }
      });

      let hovered = null;
      m.on("mousemove", "fld-fill", (e) => {
        m.getCanvas().style.cursor = "pointer";
        const f = e.features[0];
        if (hovered && hovered !== f.id) m.setFeatureState({ source: "fields", id: hovered }, { hover: false });
        hovered = f.id;
        m.setFeatureState({ source: "fields", id: hovered }, { hover: true });
        onHoverField(f.properties.id);
        popup.current
          .setLngLat(e.lngLat)
          .setHTML(
            `<div style="font-family:${FONT_DATA};font-size:11px;line-height:1.6">
               <div style="font-weight:700;font-size:13px;color:${C.ink}">FARMER ID XXXXX</div>
               <div style="color:${C.mute}">${f.properties.villageName} - XXS ha - ${f.properties.millerName}</div>
             </div>`
          )
          .addTo(m);
      });
      m.on("mouseleave", "fld-fill", () => {
        m.getCanvas().style.cursor = "";
        if (hovered) m.setFeatureState({ source: "fields", id: hovered }, { hover: false });
        hovered = null;
        onHoverField(null);
        popup.current.remove();
      });
      /* clicking bare map (not on a parcel) clears the pin */
      m.on("click", (e) => {
        if (levelRef.current !== "village") return;
        if (m.queryRenderedFeatures(e.point, { layers: ["fld-fill"] }).length) return;
        onPickField(null);
      });

      m.on("click", "fld-fill", (e) => {
        e.preventDefault();                       // don't let it reach pb-fill
        e.originalEvent.stopPropagation();
        const p = e.features[0].properties;
        if (levelRef.current === "district") {
          onZoomToField(p.village, p.id);          // zoom into its village, pinned on arrival
        } else {
          onPickField(p.id);                       // village level: pin it - camera does NOT move
        }
      });

      setReady(true);
    });

    // The map column sits in a CSS grid next to the detail panel, and web
    // fonts/layout can still reflow its width after this effect first runs.
    // resize() alone only re-reads the container's pixel size - it keeps
    // whatever centre/zoom fitBounds computed against the OLD (possibly
    // still-settling) size, which is exactly how India ends up off-centre
    // or cropped. Re-fitting after every resize recomputes that centre/zoom
    // against the container's current size, so India (or whatever level is
    // active) stays properly framed through any later layout shift.
    const ro = new ResizeObserver(() => {
      m.resize();
      refitCamera(m);
    });
    ro.observe(holder.current);

    return () => { ro.disconnect(); m.remove(); map.current = null; };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  /* --- camera + layer visibility per level ------------------------------ */
  useEffect(() => {
    const m = map.current;
    if (!m || !ready) return;

    const showDistrict = level === "district" || level === "village";
    // At the punjab level the district shape (Ludhiana & Faridkot) is its
    // own clickable, highlighted sub-area - not just an outline you can't
    // interact with until you're already past it.
    m.setPaintProperty("pd-fill", "fill-opacity", level === "punjab" ? 0.4 : showDistrict ? 0.14 : 0);
    m.setPaintProperty("pd-line", "line-opacity", level === "punjab" || showDistrict ? 1 : 0);
    m.setPaintProperty("pb-fill", "fill-opacity", level === "india" ? 0.34 : level === "punjab" ? 0.22 : 0.1);

    m.setFilter("fld-fill", showDistrict ? true : ["==", ["get", "village"], ""]);
    m.setFilter("fld-line", showDistrict ? true : ["==", ["get", "village"], ""]);

    refitCamera(m, { duration: 1800 });
  }, [level, village, focusedDistrict, ready, refitCamera]);

  /* --- village pins: small pulsing red dot, one per village --------------
     MapLibre writes its own inline `transform: translate(...)` onto the
     marker's ROOT element to keep it pinned to lng/lat - the halo pulse and
     hover scale live on an inner wrapper instead, or the marker jumps to
     the map's top-left corner the moment either animation touches `el`.
     We deliberately don't bake the village name into the marker (the
     basemap's own place labels sit under it for villages it recognises;
     the clickable name+count legend below the map covers the rest, since
     many of these 126 hamlet-level villages aren't in the basemap at all)
     - a native `title` tooltip gives the name on hover regardless. */
  useEffect(() => {
    const m = map.current;
    if (!m || !ready) return;
    markers.current.forEach((mk) => mk.remove());
    markers.current = [];
    if (level !== "district") return;

    VILLAGES.forEach((v) => {
      const el = document.createElement("div");
      el.style.cssText = "width:16px;height:16px;cursor:pointer;";
      const inner = document.createElement("button");
      inner.setAttribute("aria-label", `${v.name} - XXS fields`);
      inner.title = `${v.name} - XXS fields`;
      inner.style.cssText = `position:relative;width:16px;height:16px;padding:0;border:0;background:none;
        cursor:pointer;display:block;transition:transform .15s ease;`;
      inner.innerHTML = `
        <span style="position:absolute;inset:0;border-radius:99px;background:${C.husk};opacity:.55;
          animation:wh-village-pulse 2.2s ease-out infinite;"></span>
        <span style="position:absolute;top:3px;left:3px;width:10px;height:10px;border-radius:99px;
          background:${C.husk};border:2px solid #fff;box-shadow:0 2px 6px rgba(0,0,0,.45);"></span>`;
      inner.onmouseenter = () => { inner.style.transform = "scale(1.25)"; };
      inner.onmouseleave = () => { inner.style.transform = "none"; };
      inner.onclick = () => onPickVillage(v.key);
      el.appendChild(inner);
      markers.current.push(new Marker({ element: el }).setLngLat([v.lon, v.lat]).addTo(m));
    });
  }, [level, ready, onPickVillage]);

  /* --- selection feature-state ------------------------------------------ */
  const prevSel = useRef(null);
  useEffect(() => {
    const m = map.current;
    if (!m || !ready) return;
    if (prevSel.current) m.setFeatureState({ source: "fields", id: prevSel.current }, { selected: false });
    if (selected) m.setFeatureState({ source: "fields", id: selected }, { selected: true });
    prevSel.current = selected;
  }, [selected, ready]);

  return (
    <div className="relative rounded-lg overflow-hidden" style={{ border: `1px solid ${C.line}` }}>
      <div ref={holder} style={{ width: "100%", height: "clamp(380px, 56vh, 620px)" }} />
      {!ready && (
        <div className="absolute inset-0 flex items-center justify-center" style={{ background: C.paperDim }}>
          <span style={{ fontFamily: FONT_DATA, fontSize: 10.5, letterSpacing: ".12em", color: C.mute }}>
            LOADING BASEMAP...
          </span>
        </div>
      )}
    </div>
  );
}

